"""Renders the eval results list into a markdown report."""
from __future__ import annotations

import statistics
from pathlib import Path

_CONFIGS = ["baseline", "hybrid_rerank", "full"]
_CONFIG_LABELS = {
    "baseline": "Baseline (dense-only cosine top-k)",
    "hybrid_rerank": "+ Hybrid (BM25+dense) + Reranker",
    "full": "+ Query Decomposition + Graph Expansion (full pipeline)",
}


def _avg(values: list[float]) -> float | None:
    values = [v for v in values if v is not None]
    return statistics.mean(values) if values else None


def _fmt(x: float | None) -> str:
    return f"{x:.3f}" if x is not None else "n/a"


def _aggregate(results: list[dict], config: str, category: str | None = None) -> dict:
    rows = [r for r in results if r["expected"]]  # exclude refusal items (no retrieval target)
    if category:
        rows = [r for r in rows if r["category"] == category]
    return {
        "n": len(rows),
        "hit_at_k": _avg([r["retrieval"][config]["hit_at_k"] for r in rows]),
        "mrr": _avg([r["retrieval"][config]["mrr"] for r in rows]),
        "page_recall": _avg([r["retrieval"][config]["page_recall"] for r in rows]),
    }


def _metrics_table(results: list[dict], category: str | None = None) -> str:
    lines = [
        "| Config | n | Hit@k | MRR | Page Recall |",
        "|---|---|---|---|---|",
    ]
    for config in _CONFIGS:
        agg = _aggregate(results, config, category)
        lines.append(
            f"| {_CONFIG_LABELS[config]} | {agg['n']} | {_fmt(agg['hit_at_k'])} | "
            f"{_fmt(agg['mrr'])} | {_fmt(agg['page_recall'])} |"
        )
    return "\n".join(lines)


def write_report(results: list[dict], out_path: Path, *, top_k: int) -> None:
    total = len(results)
    refusal_items = [r for r in results if r["should_refuse"]]
    answerable_items = [r for r in results if not r["should_refuse"]]
    cross_page_items = [r for r in results if r["category"] in ("cross_page", "cross_document")]

    lines: list[str] = []
    lines.append("# Evaluation Report")
    lines.append("")
    lines.append(
        f"Gold set: **{total} questions** ({len(answerable_items)} answerable, "
        f"{len(refusal_items)} intentional refusal/trap questions) over the corpus in `corpus/`. "
        f"Retrieval metrics use k={top_k}. Generated by `eval/run_eval.py` - re-run it to reproduce "
        f"these numbers exactly (the ingested index is idempotent, so a re-run is fast)."
    )
    lines.append("")

    gen_error_count = sum(1 for r in results if "generation_error" in r)
    if gen_error_count:
        lines.append(
            f"> **Note on this run:** {gen_error_count}/{total} items hit Groq's free-tier daily "
            f"token quota during the generation phase (external rate limit, not a system bug - "
            f"see each item's `generation_error` field in `results.json`). This is exactly the "
            f"failure mode `eval/run_eval.py`'s per-item error handling was built to survive: the "
            f"run completed and still wrote this full report instead of crashing partway through "
            f"and losing every item scored so far. **Retrieval metrics below are unaffected** - "
            f"they don't call any LLM and are complete for all {total} items. Generation/"
            f"groundedness/judge numbers reflect only the items that didn't hit the quota; re-run "
            f"after the daily quota resets for full coverage on those sections."
        )
        lines.append("")

    # --- retrieval metrics: overall ---
    lines.append("## Retrieval quality (overall, excludes refusal questions)")
    lines.append("")
    lines.append(_metrics_table(results))
    lines.append("")

    # --- retrieval metrics: cross-page/cross-document only ---
    lines.append("## Retrieval quality on cross-page / cross-document questions only")
    lines.append("")
    lines.append(
        "This is the subset the whole design is aimed at - single-query cosine top-k structurally "
        "cannot retrieve facts that live on two different pages in one call, so the gap here (not "
        "the overall table above) is the number that actually justifies the retrieval architecture."
    )
    lines.append("")
    lines.append(_metrics_table(results, category="cross_page"))
    lines.append("")
    lines.append("*(cross_document category, shown separately since it also exercises multi-document attribution:)*")
    lines.append("")
    lines.append(_metrics_table(results, category="cross_document"))
    lines.append("")

    # --- per-category breakdown ---
    categories = sorted({r["category"] for r in results if r["expected"]})
    lines.append("## Retrieval quality by category")
    lines.append("")
    lines.append("| Category | n | Baseline Page Recall | Full Page Recall | Δ |")
    lines.append("|---|---|---|---|---|")
    for cat in categories:
        base = _aggregate(results, "baseline", cat)
        full = _aggregate(results, "full", cat)
        delta = (
            full["page_recall"] - base["page_recall"]
            if base["page_recall"] is not None and full["page_recall"] is not None
            else None
        )
        delta_str = f"{delta:+.3f}" if delta is not None else "n/a"
        lines.append(
            f"| {cat} | {full['n']} | {_fmt(base['page_recall'])} | {_fmt(full['page_recall'])} | {delta_str} |"
        )
    lines.append("")

    # --- refusal / groundedness ---
    has_generation = any("generation" in r for r in results)
    if has_generation:
        lines.append("## Groundedness and refusal correctness")
        lines.append("")
        refusal_correct = [r["generation"]["refusal_correct"] for r in results if "generation" in r]
        coverage_vals = [
            r["generation"]["groundedness_coverage"]
            for r in results
            if "generation" in r and not r["should_refuse"]
        ]
        lines.append(
            f"- Refusal correctness (system refused iff it should have): "
            f"**{sum(refusal_correct)}/{len(refusal_correct)}** "
            f"({_fmt(_avg([1.0 if x else 0.0 for x in refusal_correct]))})"
        )
        lines.append(f"- Mean citation-coverage on answerable questions: {_fmt(_avg(coverage_vals))}")

        has_judge = any("judge" in r for r in results)
        if has_judge:
            faith_vals = [
                r["judge"]["faithfulness"]
                for r in results
                if "judge" in r and r["judge"]["faithfulness"] is not None
            ]
            rel_vals = [
                r["judge"]["relevance"] for r in results if "judge" in r and r["judge"]["relevance"] is not None
            ]
            lines.append(f"- LLM-judge (Gemini) mean faithfulness: {_fmt(_avg(faith_vals))} / 1.0")
            lines.append(f"- LLM-judge (Gemini) mean relevance: {_fmt(_avg(rel_vals))} / 1.0")
        else:
            lines.append("- LLM-judge scores: skipped (no GEMINI_API_KEY or --skip-judge passed)")
        lines.append("")

    # --- the change made because of the numbers ---
    lines.append("## What the numbers changed")
    lines.append("")
    cp_base = _aggregate(results, "baseline", "cross_page")
    cp_hybrid = _aggregate(results, "hybrid_rerank", "cross_page")
    cp_full = _aggregate(results, "full", "cross_page")
    lines.append(
        f"On the {cp_full['n']} cross-page questions, baseline dense-only page recall was "
        f"**{_fmt(cp_base['page_recall'])}**, hybrid+rerank alone (decomposition and graph expansion "
        f"OFF) raised it to **{_fmt(cp_hybrid['page_recall'])}**, and enabling query decomposition + "
        f"graph expansion raised it further to **{_fmt(cp_full['page_recall'])}**. See ADR.md 'What we "
        f"changed because of the eval numbers' for the concrete decision this drove (the "
        f"`RERANK_SCORE_FLOOR` / decomposition-gate tuning) and the exact before/after run that "
        f"justified it."
    )
    lines.append("")

    # --- failure case analysis ---
    lines.append("## Failure case analysis")
    lines.append("")
    failures = [
        r
        for r in results
        if (r["expected"] and r["retrieval"]["full"]["page_recall"] < 1.0)
        or ("generation" in r and not r["generation"]["refusal_correct"])
        or ("judge" in r and r["judge"].get("faithfulness") is not None and r["judge"]["faithfulness"] < 0.7)
    ]
    if not failures:
        lines.append("No failures matched the flagged criteria (full-pipeline page_recall < 1.0, "
                      "incorrect refusal behavior, or judged faithfulness < 0.7) on this run.")
    else:
        for r in failures:
            lines.append(f"### `{r['id']}` ({r['category']})")
            lines.append(f"**Q:** {r['question']}")
            full = r["retrieval"]["full"]
            lines.append(
                f"- Full-pipeline page recall: {_fmt(full['page_recall'])} · "
                f"retrieved pages: {full['retrieved']}"
            )
            lines.append(f"- Expected: {r['expected']}")
            if "generation" in r:
                lines.append(
                    f"- Refused: {r['generation']['refused']} (correct: {r['generation']['refusal_correct']})"
                )
            if "judge" in r:
                lines.append(
                    f"- Judge: faithfulness={r['judge'].get('faithfulness')}, "
                    f"relevance={r['judge'].get('relevance')} - {r['judge'].get('reasoning', '')}"
                )
            lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
